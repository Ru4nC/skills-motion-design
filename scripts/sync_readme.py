#!/usr/bin/env python3
"""
Sincronizador Automático do README.md a partir das Skills de Motion Design.
Gera a tabela oficial de Agent Skills com base no YAML frontmatter de cada SKILL.md.
"""

import sys
from pathlib import Path
from typing import Dict, List, Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO_ROOT / "skills"
README_PATH = REPO_ROOT / "README.md"


def parse_frontmatter(content: str) -> Dict[str, str]:
    """Extrai campos do frontmatter YAML delimitado por ---."""
    if not content.startswith("---"):
        return {}
    parts = content.split("---", 2)
    if len(parts) < 3:
        return {}
    raw_yaml = parts[1]
    data: Dict[str, str] = {}
    for line in raw_yaml.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" in line:
            key, val = line.split(":", 1)
            data[key.strip()] = val.strip().strip("\"'")
    return data


def gather_skills() -> List[Tuple[str, str, str]]:
    """Lê todas as skills disponíveis em skills/ e retorna lista ordenada de (slug, name, description)."""
    skills = []
    if not SKILLS_DIR.exists():
        return skills

    for folder in sorted(SKILLS_DIR.iterdir(), key=lambda x: x.name):
        if not folder.is_dir() or folder.name.startswith("."):
            continue
        skill_md = folder / "SKILL.md"
        if not skill_md.exists():
            continue
        meta = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        name = meta.get("name", folder.name)
        description = meta.get("description", "Motion design skill.")
        skills.append((folder.name, name, description))
    return skills


def generate_readme_content(skills: List[Tuple[str, str, str]]) -> str:
    """Gera o markdown completo para o README.md."""
    lines = [
        "<!-- This file is automatically generated by scripts/sync_readme.py. -->",
        "",
        "# Python Motion Design Agent Skills",
        "",
        "Coleção oficial de **Agent Skills** para agentes de IA (Claude Code, Cursor, Antigravity, Codex) projetada sob uma arquitetura **Python-First** (100% contida em `.venv/bin/python`, determinística e offline).",
        "",
        "A suíte é desenvolvida diretamente em **Pillow (PIL) + NumPy**, com streaming contínuo de quadros em memória para o **FFmpeg** gerando clipes transparentes (`.webm` VP9 `yuva420p` com canal alfa real) em ~1.5s por animação, e composição na timeline via `filter_complex` com PTS Shift.",
        "",
        "## Arquitetura da Stack",
        "",
        "- **Motor Gráfico em Memória**: Síntese direta quadro a quadro via Pillow (`ImageDraw`, `ImageFont`) e transformações matriciais com NumPy em buffers rawvideo RGBA.",
        "- **Streaming sem Arquivos Temporários**: Eliminação de PNGs intermediários em disco através de pipes stdin para o binário FFmpeg.",
        "- **Overlays com Canal Alfa Real**: Codec VP9 (`libvpx-vp9`), formato de pixel `yuva420p` com flag `-auto-alt-ref 0`.",
        "- **Composição na Timeline**: Sobreposição via `filter_complex` com PTS Shift (`setpts=PTS-STARTPTS+{t_start}/TB`) para sincronia precisa sem congelamento de quadros.",
        "- **Prototipagem em Notebooks**: Suporte nativo a Google Colab e Jupyter com visualizador `InlineAlphaPreview` sob fundo quadriculado.",
        "",
        "## Catálogo de Skills Disponíveis",
        "",
    ]

    for slug, name, description in skills:
        lines.append(f"### `/{name}`")
        lines.append("")
        lines.append(description)
        lines.append("")
        lines.append(f"> Pasta: [`skills/{slug}/`](./skills/{slug}/SKILL.md)")
        lines.append("")

    lines.extend([
        "## Uso com Agentes de IA",
        "",
        "Para utilizar estas skills em seu agente de codificação, adicione o caminho deste repositório à configuração de skills do agente (ex.: Claude Code, Antigravity ou Cursor).",
        "",
        "```bash",
        "# Validar integridade das skills",
        "python scripts/validate_skills.py",
        "",
        "# Atualizar documentação e índices",
        "python scripts/sync_readme.py",
        "```",
        "",
    ])

    return "\n".join(lines)


def sync_readme() -> int:
    """Executa a sincronização do README.md."""
    skills = gather_skills()
    content = generate_readme_content(skills)
    README_PATH.write_text(content, encoding="utf-8")
    print(f"README.md sincronizado com sucesso com {len(skills)} skills detectadas.")
    return 0


if __name__ == "__main__":
    sys.exit(sync_readme())
