def parse_frontmatter(content: str) -> Dict[str, str]:
    """Extrai campos do frontmatter YAML delimitado por ---."""
    if not content.startswith("---"):
        return {}
    parts = content.split("---", 2)
    if len(parts) < 3:
        return {}
    raw_yaml = parts[1]
    data: Dict[str, str] = {}
    for line in raw_yaml.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" in line:
            key, val = line.split(":", 1)
            data[key.strip()] = val.strip().strip("\"'")
    return data


def gather_skills() -> List[Tuple[str, str, str]]:
    """Lê todas as skills disponíveis em skills/ e retorna lista ordenada de (slug, name, description)."""
    skills = []
    if not SKILLS_DIR.exists():
        return skills

    for folder in sorted(SKILLS_DIR.iterdir(), key=lambda x: x.name):
        if not folder.is_dir() or folder.name.startswith("."):
            continue
        skill_md = folder / "SKILL.md"
        if not skill_md.exists():
            continue
        meta = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        name = meta.get("name", folder.name)
        description = meta.get("description", "Motion design skill.")
        skills.append((folder.name, name, description))
    return skills


